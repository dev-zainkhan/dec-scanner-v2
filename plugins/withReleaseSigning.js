// Signs release builds with the Play upload key described in signing.properties at the
// project root (created by `npm run create-upload-key`, git-ignored):
//
//   storeFile=keys/upload-key.jks
//   storePassword=...
//   keyAlias=upload
//   keyPassword=...
//
// Without that file, release builds fall back to the debug key so they can still be
// installed locally (Play Console rejects debug-signed bundles).
const { withAppBuildGradle } = require('expo/config-plugins');

const MARKER = 'signing.properties';

const LOAD_PROPERTIES = `
// Play upload key (see plugins/withReleaseSigning.js)
def releaseSigning = new Properties()
def releaseSigningFile = new File(rootDir, '../signing.properties')
if (releaseSigningFile.exists()) {
    releaseSigningFile.withInputStream { releaseSigning.load(it) }
}
`;

const RELEASE_SIGNING = `
        release {
            if (releaseSigningFile.exists()) {
                def keystore = new File(releaseSigning['storeFile'])
                storeFile keystore.isAbsolute() ? keystore : new File(rootDir, '../' + releaseSigning['storeFile'])
                storePassword releaseSigning['storePassword']
                keyAlias releaseSigning['keyAlias']
                keyPassword releaseSigning['keyPassword']
            }
        }`;

// The top-level `android {` block, the debug signing config, and the release build
// type's `signingConfig signingConfigs.debug` line generated by Expo prebuild.
const ANDROID_BLOCK = /\nandroid \{/;
const DEBUG_SIGNING = /(signingConfigs \{\s*debug \{[^}]*\})/;
const RELEASE_USES_DEBUG = /(release \{\s*(?:\/\/[^\n]*\n\s*)*)signingConfig signingConfigs\.debug/;

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    const gradle = cfg.modResults.contents;
    if (gradle.includes(MARKER)) return cfg;
    if (![ANDROID_BLOCK, DEBUG_SIGNING, RELEASE_USES_DEBUG].every((re) => re.test(gradle))) {
      throw new Error('withReleaseSigning: android/app/build.gradle no longer matches the expected template.');
    }
    cfg.modResults.contents = gradle
      .replace(ANDROID_BLOCK, `${LOAD_PROPERTIES}\nandroid {`)
      .replace(DEBUG_SIGNING, `$1${RELEASE_SIGNING}`)
      .replace(
        RELEASE_USES_DEBUG,
        '$1signingConfig releaseSigningFile.exists() ? signingConfigs.release : signingConfigs.debug',
      );
    return cfg;
  });
};
