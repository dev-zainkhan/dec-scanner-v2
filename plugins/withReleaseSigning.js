// Signs release builds with the Play upload key when it is configured in
// %USERPROFILE%\.gradle\gradle.properties (never in this repo):
//
//   SCANOVA_UPLOAD_STORE_FILE=C:/Users/<you>/keys/scanova-upload.jks
//   SCANOVA_UPLOAD_STORE_PASSWORD=...
//   SCANOVA_UPLOAD_KEY_ALIAS=scanova-upload
//   SCANOVA_UPLOAD_KEY_PASSWORD=...
//
// Without those properties, release builds fall back to the debug key so they can
// still be installed locally (Play Console rejects debug-signed bundles).
const { withAppBuildGradle } = require('expo/config-plugins');

const PROP = 'SCANOVA_UPLOAD_STORE_FILE';

// The debug signing config block generated by Expo prebuild.
const DEBUG_SIGNING = /(signingConfigs \{\s*debug \{[^}]*\})/;
// The release build type's `signingConfig signingConfigs.debug` line (after its comments).
const RELEASE_USES_DEBUG = /(release \{\s*(?:\/\/[^\n]*\n\s*)*)signingConfig signingConfigs\.debug/;

const RELEASE_SIGNING = `
        release {
            if (project.hasProperty('${PROP}')) {
                storeFile file(${PROP})
                storePassword SCANOVA_UPLOAD_STORE_PASSWORD
                keyAlias SCANOVA_UPLOAD_KEY_ALIAS
                keyPassword SCANOVA_UPLOAD_KEY_PASSWORD
            }
        }`;

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    const gradle = cfg.modResults.contents;
    if (gradle.includes(PROP)) return cfg;
    if (!DEBUG_SIGNING.test(gradle) || !RELEASE_USES_DEBUG.test(gradle)) {
      throw new Error('withReleaseSigning: android/app/build.gradle no longer matches the expected template.');
    }
    cfg.modResults.contents = gradle
      .replace(DEBUG_SIGNING, `$1${RELEASE_SIGNING}`)
      .replace(
        RELEASE_USES_DEBUG,
        `$1signingConfig project.hasProperty('${PROP}') ? signingConfigs.release : signingConfigs.debug`,
      );
    return cfg;
  });
};
